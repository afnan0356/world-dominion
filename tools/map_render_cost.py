#!/usr/bin/env python3
"""Count what one map frame is made of, without running the engine.

This is a *model*, not a GPU capture: it reads the committed atlas data and the
renderer's own constants, then counts the drawing work a fitted 1280x720 frame
asks for. It exists so a change to the map can be argued with numbers instead of
impressions, and so the numbers in `docs/MAP_RENDERING.md` can be regenerated by
anyone rather than copied out of a chat log.

`--before` models the Milestone 03 renderer: one flat land colour, no graticule,
no reference lines, no selection cues, no legend, no ocean texture. Everything
else — the fills, the border polylines, the labels, the capitals, the scale bar —
is identical in both, because those are the parts this milestone did not change.

Real frame timings need a GPU; this script never pretends to measure a frame rate.
"""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VIEW_WIDTH = 1280
VIEW_HEIGHT = 720


def read_constants() -> dict:
    """Pull the projection and camera constants out of the GDScript sources."""
    text = (ROOT / "src/core/world/map_projection.gd").read_text(encoding="utf-8")
    values = {}
    for name in ("MIN_LON", "MAX_LON", "MIN_LAT", "MAX_LAT", "GRATICULE_STEP"):
        match = re.search(rf"const {name} := (-?\d+(?:\.\d+)?)", text)
        if not match:
            raise SystemExit(f"cannot find MapProjection.{name}")
        values[name] = float(match.group(1))
    view = (ROOT / "src/ui/map/world_map_view.gd").read_text(encoding="utf-8")
    for name in ("LABEL_LIMIT", "LABEL_LIMIT_SPARSE", "REFERENCE_DASH_PX",
                 "OCEAN_LABELS"):
        match = re.search(rf"const {name} := (.+)", view)
        if not match:
            continue
        raw = match.group(1).strip()
        if raw.isdigit():
            values[name] = int(raw)
    latitudes = re.search(r"const REFERENCE_LATITUDES := \[(.*?)\]", view, re.S)
    values["reference_lines"] = len(re.findall(r"-?\d+\.?\d*", latitudes.group(1)))
    values["ocean_labels"] = len(re.findall(r'\["',
                                  re.search(r"const OCEAN_LABELS := \[(.*?)\n\]",
                                            view, re.S).group(1)))
    return values


def load() -> tuple:
    geometry = json.loads((ROOT / "data/world/geometry.json").read_text(encoding="utf-8"))
    countries = json.loads((ROOT / "data/world/countries.json").read_text(encoding="utf-8"))
    coast = json.loads((ROOT / "data/world/coast.json").read_text(encoding="utf-8"))
    return geometry, countries, coast


def count(before: bool) -> dict:
    constants = read_constants()
    geometry, countries, coast = load()
    ids = [entry["id"] for entry in countries["countries"]]

    rings = 0
    coast_rings = 0
    land_rings = 0
    mixed_rings = 0
    vertices = 0
    for country_id in ids:
        polygons = geometry["countries"][country_id]["polygons"]
        codes = coast["countries"].get(country_id, "")
        index = 0
        for polygon in polygons:
            for ring in polygon:
                rings += 1
                vertices += len(ring) // 2
                code = codes[index] if index < len(codes) else "0"
                if code == "1":
                    coast_rings += 1
                elif code == "2":
                    mixed_rings += 1
                else:
                    land_rings += 1
                index += 1

    visible = len(ids)
    labels = min(constants.get("LABEL_LIMIT", 26),
                 sum(1 for entry in countries["countries"]
                     if entry.get("label") is not None and entry.get("label_rank", 9) <= 2))
    capitals = sum(1 for entry in countries["countries"] if entry.get("capital") is not None)

    lon_lines = int((constants["MAX_LON"] - constants["MIN_LON"])
                    / constants["GRATICULE_STEP"]) + 1
    lat_lines = int((constants["MAX_LAT"] - constants["MIN_LAT"])
                    / constants["GRATICULE_STEP"]) + 1
    # One dash every 12 px: 6 px drawn, 6 px gap (`_draw_reference_lines`).
    reference_dashes = constants["reference_lines"] * int(VIEW_WIDTH / 12.0)

    # One entry = one drawing command. Since Milestone 04 the grid, the reference
    # dashes, the selection ticks, the legend samples and the scale bar ticks are
    # each a single batched `draw_multiline`, which is why the new layers cost a
    # handful of commands instead of one per line.
    frame = {
        "ocean texture": 1,
        "country fills": visible * 2,
        "border polylines": rings,
        "label halos": labels,
        "label texts": labels,
        "capital markers": capitals,
        "ocean labels": constants["ocean_labels"],
        "scale bar": 2 if not before else 4,
        "graticule grid": 0 if before else (1 if lon_lines + lat_lines else 0),
        "reference dashes": 0 if before else (1 if reference_dashes else 0),
        "selection cues": 0 if before else 1,
        "legend": 0 if before else 4,
        "focus ring": 1,
    }
    return {
        "frame": frame,
        "rings": rings,
        "coast_rings": coast_rings,
        "land_rings": land_rings,
        "mixed_rings": mixed_rings,
        "vertices": vertices,
        "meshes": visible * 2,
        "graticule lines": lon_lines + lat_lines,
        "reference dashes": reference_dashes,
        "labels": labels,
    }


def table(result: dict) -> str:
    frame = result["frame"]
    total = sum(frame.values())
    lines = ["| Draw command | Count |", "| --- | ---: |"]
    for name, value in frame.items():
        lines.append(f"| {name} | {value:,} |")
    lines.append(f"| **total** | **{total:,}** |")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--before", action="store_true",
                        help="model the Milestone 03 renderer instead of the current one")
    parser.add_argument("--json", action="store_true", help="print the raw numbers")
    args = parser.parse_args()
    result = count(args.before)
    if args.json:
        print(json.dumps(result, indent=2))
        return 0
    print(f"model of one fitted {VIEW_WIDTH}x{VIEW_HEIGHT} frame"
          f" ({'Milestone 03' if args.before else 'current'} renderer)")
    print(table(result))
    print(f"\nlabels drawn {result['labels']}, graticule lines {result['graticule lines']}, "
          f"reference dashes {result['reference dashes']}")
    print(f"rings {result['rings']:,} "
          f"({result['coast_rings']:,} coastline, {result['land_rings']:,} land border, "
          f"{result['mixed_rings']:,} mixed), vertices {result['vertices']:,}, "
          f"cached meshes {result['meshes']:,}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
