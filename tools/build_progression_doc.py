#!/usr/bin/env python3
"""Generate docs/PROGRESSION.md from the XP curve, and check it is still true.

The curve lives in `src/core/profile/progression.gd` because the game needs it at runtime.
This tool carries the same formula in Python so the *document* can be regenerated and
checked in CI — and, because two copies of a formula drift, it embeds a machine-readable
block that the GDScript suite verifies against the real implementation. If either copy
changes on its own, one of the two gates fails.

    python3 tools/build_progression_doc.py            # write the document
    python3 tools/build_progression_doc.py --check    # fail when it is stale
    python3 tools/build_progression_doc.py --self-test
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "PROGRESSION.md"

MAX_LEVEL = 1000
#: XP needed to advance FROM each of the first five levels: 0->1 costs 100, 1->2 costs 200,
#: 2->3 costs 250, 3->4 costs 300, 4->5 costs 500. The cost per level never dips.
LEVEL_COSTS = [100, 200, 250, 300, 500]
COST_STEP = 50
VIP_LEVELS = [0, 25, 50, 75, 100, 150, 200, 300, 500, 750, 1000]
MAX_VIP = 10
VIP_SPEED_TIER = 5
TUTORIAL_XP = 100
TUTORIAL_GOLD = 100
TUTORIAL_DIAMONDS = 25
SPEED_MAX = 2
SPEED_MAX_VIP = 3
SPEED_LABELS = {1: "Normal", 2: "Fast-forward", 3: "VIP fast-forward"}
#: One tick is one in-game day, so these are days per real second.
TICKS_PER_SECOND = {1: 1.0, 2: 10.0, 3: 20.0}

#: Levels whose totals go into the table and into the cross-check block.
SAMPLED_LEVELS = list(range(1, 11)) + VIP_LEVELS[1:] + [MAX_LEVEL]


def increment(level: int) -> int:
    if level <= 0:
        return 0
    if level <= len(LEVEL_COSTS):
        return LEVEL_COSTS[level - 1]
    return LEVEL_COSTS[-1] + COST_STEP * (level - 5)


def xp_to_reach(level: int) -> int:
    if level <= 0:
        return 0
    if level <= len(LEVEL_COSTS):
        return sum(LEVEL_COSTS[:level])
    steps = level - 5
    return sum(LEVEL_COSTS) + 500 * steps + 25 * steps * (steps + 1)


def level_for_xp(xp: int) -> int:
    if xp <= 0:
        return 0
    low, high = 0, MAX_LEVEL
    while low < high:
        middle = (low + high + 1) // 2
        if xp_to_reach(middle) <= xp:
            low = middle
        else:
            high = middle - 1
    return low


def vip_for_level(level: int) -> int:
    tier = 0
    for index, threshold in enumerate(VIP_LEVELS):
        if level >= threshold:
            tier = index
    return max(0, min(tier, MAX_VIP))


def document() -> str:
    lines: list[str] = []
    add = lines.append
    add("# Progression: XP, levels, VIP and speed")
    add("")
    add("Generated by `python3 tools/build_progression_doc.py` from the same formula the game")
    add("uses. CI runs it with `--check` and fails when this file and the curve disagree, and")
    add("the test suite cross-checks the numbers below against `src/core/profile/progression.gd`.")
    add("")
    add("> **Every number on this page is an owner-reviewable default.** The curve is a design")
    add("> choice, not a measurement. Changing it means changing one constant and regenerating")
    add("> this page; nothing else in the game depends on the exact values.")
    add("")
    add("## The rules")
    add("")
    add("* Progression belongs to the **profile**, not to a world. A new campaign keeps the")
    add("  player's level, name and wallet.")
    add("* The XP needed to advance **from** each of the first five levels is 100, 200, 250,")
    add("  300 and 500 — the cost of a level rises at every step, with no dip.")
    add("* Above level 5 it keeps rising by a fixed extra 50 per level:")
    add("  `increment(n) = 500 + 50 × (n − 5)`, so the cost per level is **strictly")
    add("  increasing across all 1000 levels**.")
    add("* The highest level is 1000. Its total is %d XP." % xp_to_reach(MAX_LEVEL))
    add("* VIP is derived from the level and never stored, so a profile file cannot claim a")
    add("  tier it has not earned.")
    add("* VIP never locks essential gameplay. The only thing it unlocks is **one** extra")
    add("  speed at VIP 5, worth exactly double the shipped top speed.")
    add("")
    add("## The formula")
    add("")
    add("```")
    add("increment(n)     = 100, 200, 250, 300, 500                    for n = 1..5")
    add("increment(n)     = 500 + 50 × (n − 5)                         for n ≥ 6")
    add("xp_to_reach(n)   = 100, 300, 550, 850, 1350                   for n = 1..5")
    add("xp_to_reach(n)   = 1,350 + 500 × (n − 5) + 25 × (n − 5) × (n − 4)   for n ≥ 5")
    add("```")
    add("")
    add("## Levels")
    add("")
    add("| Level | XP to reach it | XP needed for it |")
    add("| ---: | ---: | ---: |")
    for level in SAMPLED_LEVELS:
        add("| %d | %s | %s |" % (level, f"{xp_to_reach(level):,}",
                                 f"{increment(level):,}"))
    add("")
    add("## VIP tiers")
    add("")
    add("| VIP | Starts at level | Total XP | Unlocks |")
    add("| ---: | ---: | ---: | --- |")
    for tier in range(MAX_VIP + 1):
        level = VIP_LEVELS[tier]
        total = xp_to_reach(level) if level > 0 else 0
        unlocks = "the extra speed" if tier == VIP_SPEED_TIER else "—"
        if tier > VIP_SPEED_TIER:
            unlocks = "nothing further (VIP %d has the extra speed too)" % VIP_SPEED_TIER
        add("| %d | %s | %s | %s |" % (tier, level, f"{total:,}", unlocks))
    add("")
    add("VIP 8 and 9 are proposals: the levels exist, and there is deliberately nothing")
    add("behind them yet. A tier that unlocks nothing is honest; a tier that unlocks an")
    add("advantage nobody can earn by playing would not be.")
    add("")
    add("## Speeds")
    add("")
    add("| Speed | Name | Days per real second | Who has it |")
    add("| ---: | --- | ---: | --- |")
    for speed in range(1, SPEED_MAX + 1):
        ticks = TICKS_PER_SECOND[speed]
        add("| %d | %s | %g | everyone |" % (speed, SPEED_LABELS[speed], ticks))
    add("| %d | %s | %g | VIP %d and above |"
        % (SPEED_MAX_VIP, SPEED_LABELS[SPEED_MAX_VIP], TICKS_PER_SECOND[SPEED_MAX_VIP],
           VIP_SPEED_TIER))
    add("")
    add("Pause is speed 0 and is always available. The default is **Normal**: one in-game day")
    add("per real second. Speeds store a stable id (`paused`, `normal`, `fast_forward`,")
    add("`vip_fast_forward`), so a save names its speed rather than a number that could be")
    add("re-used. Saves written before the three-speed set stored a number, and")
    add("`GameClock.migrate_legacy_speed()` maps it: old 1 stays 1, old 2 stays 2, old 3 and 4")
    add("become 2 (the nearest speed everyone has). A migration never grants the VIP speed.")
    add("")
    add("Speeds are **tick-based**: a speed is a number of simulation ticks per real second,")
    add("and one tick is one in-game day, so the same number of ticks always produces the same")
    add("date. The extra speed changes how long the player waits, never what the simulation")
    add("computes.")
    add("")
    add("## Tutorial reward")
    add("")
    add("Paid once per profile, ever — completing the tutorial again pays nothing:")
    add("")
    add("| Reward | Amount |")
    add("| --- | ---: |")
    add(f"| XP | {TUTORIAL_XP} |")
    add(f"| Gold Coins | {TUTORIAL_GOLD} |")
    add(f"| Diamonds | {TUTORIAL_DIAMONDS} |")
    add("")
    add("Skipping pays nothing and does not lock the tutorial away.")
    add("")
    add("## Where these numbers live")
    add("")
    add("* `src/core/profile/progression.gd` — the implementation the game runs.")
    add("* `src/core/profile/player_profile.gd` — XP, level, tutorial rewards, name costs.")
    add("* `tests/suites/test_progression.gd` — first five values, monotonicity across all")
    add("  1000 levels, VIP boundaries, the speed unlock, determinism, and a cross-check of")
    add("  the numbers in this document.")
    add("")
    add("<!-- progression-data")
    add(json.dumps({
        "max_level": MAX_LEVEL,
        "max_vip": MAX_VIP,
        "vip_levels": VIP_LEVELS,
        "sampled": {str(level): xp_to_reach(level) for level in SAMPLED_LEVELS},
        "tutorial": {"xp": TUTORIAL_XP, "gold": TUTORIAL_GOLD, "diamonds": TUTORIAL_DIAMONDS},
        "speed": {"max": SPEED_MAX, "vip_max": SPEED_MAX_VIP,
                  "vip_tier": VIP_SPEED_TIER,
                  "increment_base": LEVEL_COSTS[-1], "cost_step": COST_STEP,
                  "ticks": {str(key): value for key, value in TICKS_PER_SECOND.items()}},
    }, indent=2, sort_keys=True))
    add("-->")
    add("")
    return "\n".join(lines)


def self_test() -> int:
    failures: list[str] = []
    if [increment(level) for level in range(1, 6)] != LEVEL_COSTS:
        failures.append("the first five per-level costs are not the specified ones")
    if [xp_to_reach(level) for level in range(1, 6)] != [100, 300, 550, 850, 1350]:
        failures.append("the first five cumulative totals are wrong")
    # The cost of one level rises at every step, with no dip, across the whole curve.
    previous = increment(1)
    for level in range(2, MAX_LEVEL + 1):
        step = increment(level)
        if step < previous:
            failures.append(f"the cost per level decreases at level {level}")
            break
        previous = step
    for level in range(1, MAX_LEVEL + 1):
        if xp_to_reach(level) <= xp_to_reach(level - 1):
            failures.append(f"the total does not rise at level {level}")
            break
    for level in (1, 5, 25, 150, 1000):
        if level_for_xp(xp_to_reach(level)) != level:
            failures.append(f"the level lookup does not invert the curve at level {level}")
    if vip_for_level(24) != 0 or vip_for_level(25) != 1 or vip_for_level(1000) != 10:
        failures.append("the VIP boundaries are wrong")
    if xp_to_reach(MAX_LEVEL) <= 0:
        failures.append("level 1000 has no total")
    if failures:
        for message in failures:
            print(f"FAIL {message}")
        print(f"self-test: {len(failures)} failures")
        return 1
    print(f"self-test: ok (level 1000 needs {xp_to_reach(MAX_LEVEL):,} XP)")
    return 0


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args(argv[1:])
    if args.self_test:
        return self_test()
    text = document()
    try:
        committed = DOC.read_text(encoding="utf-8")
    except OSError:
        committed = None
    if args.check:
        if committed != text:
            print("error: docs/PROGRESSION.md is stale; run "
                  "python3 tools/build_progression_doc.py", file=sys.stderr)
            return 1
        print(f"progression doc is up to date (level {MAX_LEVEL} needs "
              f"{xp_to_reach(MAX_LEVEL):,} XP, {MAX_VIP + 1} VIP tiers)")
        return 0
    DOC.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {DOC.relative_to(ROOT)} (level {MAX_LEVEL} needs {xp_to_reach(MAX_LEVEL):,} XP)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
